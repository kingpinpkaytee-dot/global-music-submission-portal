-- Hourly global opportunity discovery audit trail.
BEGIN;
CREATE TABLE IF NOT EXISTS public.opportunity_discovery_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  status text NOT NULL DEFAULT 'running' CHECK (status IN ('running','completed','partial','failed')),
  searches_run integer NOT NULL DEFAULT 0,
  candidates_seen integer NOT NULL DEFAULT 0,
  records_added integer NOT NULL DEFAULT 0,
  records_updated integer NOT NULL DEFAULT 0,
  records_rejected integer NOT NULL DEFAULT 0,
  error_summary text
);
CREATE TABLE IF NOT EXISTS public.opportunity_discovery_candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id bigint REFERENCES public.opportunity_discovery_runs(id) ON DELETE SET NULL,
  category text NOT NULL,
  name text NOT NULL,
  destination_url text NOT NULL,
  submission_url text,
  evidence text,
  verification_status text NOT NULL DEFAULT 'pending' CHECK (verification_status IN ('pending','verified','rejected')),
  verification_reason text,
  discovered_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(category, destination_url)
);
CREATE INDEX IF NOT EXISTS opportunity_discovery_candidates_status_idx
  ON public.opportunity_discovery_candidates(verification_status, discovered_at DESC);
ALTER TABLE public.opportunity_discovery_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.opportunity_discovery_candidates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.opportunity_discovery_runs FROM anon, authenticated;
REVOKE ALL ON public.opportunity_discovery_candidates FROM anon, authenticated;
COMMIT;
